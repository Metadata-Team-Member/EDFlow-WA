#!/usr/bin/env node
// Generates docs/ESTABLISHMENTS.md from data/reference/establishments.json (built by tools/build_establishments.mjs from
// data/reference/official_eddc_reporting_2026-05.json). Run: npm run establishments
import { readFileSync, writeFileSync } from 'node:fs';
import { tierOf } from './lib_ref.mjs';

const J = JSON.parse(readFileSync(new URL('../data/reference/establishments.json', import.meta.url)));
const OFF = JSON.parse(readFileSync(new URL('../data/reference/official_eddc_reporting_2026-05.json', import.meta.url)));
const E = J.establishments.map((e) => ({ ...e, tier: tierOf(e) }));
const order = ['NMHS', 'SMHS', 'EMHS', 'CAHS', 'WACHS'];
const TIER = { TERT: 'teaching hospital', PAED: 'children’s hospital', WOMN: 'women’s hospital', METR: 'metropolitan hospital', REGL: 'regional hospital', DIST: 'district hospital / MPS', POST: 'nursing post', VIRT: 'virtual ED', ALIAS: 'second code, no activity' };
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const count = (f) => E.reduce((a, e) => ((a[f(e)] = (a[f(e)] || 0) + 1), a), {});
const types = count((e) => (e.type ? `${e.type} ${e.typeLabel}` : '(no Est type: code not in the List’s Hospital Morbidity System Codes table)'));
const tiers = count((e) => e.tier);
const locFlag = E.filter((e) => e.locationStatus !== 'slip');
const hspNon = E.filter((e) => e.hspBasis !== 'slip');
const also = Object.keys(OFF.totals).filter((k) => k !== 'EDDC');
const sites = new Set(E.filter((e) => e.tier !== 'ALIAS').map((e) => e.code)).size;

let m = `# Establishments in the simulation: Reports to EDDC = Y (official List, May 2026)

<!-- Generated by tools/build_establishments_doc.mjs. Edit the generator, not this file. -->

**${E.length} establishment codes, ${sites} sites.** The simulation's reporting sites are *exactly* the establishments with **Reports to EDDC = Y** in the WA Health *Establishment List*, May 2026 (v0.1), as supplied to this project by its user. Peel Health Campus appears under two codes (0145 and 0645), so ${E.length} codes cover ${sites} sites, of which ${E.filter((e) => e.tier === 'VIRT').length} (WA Virtual Hospital, 0123) is a virtual emergency department with no physical ED. Sources are in [SOURCES.md](SOURCES.md).

## How the list was read and checked

* \`tools/extract_establishment_list.py\` reads the List's "Establishment List, Reporting" table (${OFF.reportingRows} rows) **twice, independently**: once from \`pdftotext -layout\` (each Y goes to the nearest column header) and once from \`pdftotext -bbox\` (each Y's x-position is compared with the EDDC and HMDC header positions). The two reads must agree or the script stops. Both give **${OFF.totals.EDDC} rows with EDDC = Y**.
* Applied to the NADC column, the same method gives ${OFF.totals.NADC}, the count the sister project OutpatientFlow-WA uses.
* Cross-check against SLIP (Landgate HEALTH-001, which has its own "ED" flag): ${J.slipCrossCheck.slipEdFlagY} SLIP sites are flagged ED. Codes in the List but not flagged ED in SLIP: ${J.slipCrossCheck.inListNotSlipEd.map((c) => `${c} ${E.find((e) => e.code === c)?.name}`).join('; ')}. SLIP sites flagged ED but **not** in the List's EDDC set: ${J.slipCrossCheck.inSlipNotInList.map((x) => `${x.estabId} ${x.name}`).join('; ')} (see [OPEN-QUESTIONS.md](OPEN-QUESTIONS.md)).
* The other collections these sites also report to (from the same table): ${also.map((k) => `${k} ${E.filter((e) => e.alsoReports[k]).length}`).join(', ')}.

## What is official and what is not

| Field | Where it comes from | Official? |
|---|---|---|
| **Code**, **Name**, **Reports to EDDC = Y** | Establishment List May 2026, "Establishment List, Reporting" table | **Yes** |
| **Type** (AH, NP, OH) and **MPS** flag | Same document: Hospital Morbidity System Codes table (Est type) and Multi-Purpose Services appendix | **Yes** (${E.filter((e) => e.type).length} of ${E.length}; ${E.filter((e) => !e.type).length} code has no Est type) |
| **HSP** (Health Service Provider) | **Not in the List.** SLIP HEALTH-001 geographic service, with overrides noted below | **No** |
| **Region, district, beds, suburb** | **Not in the List.** SLIP HEALTH-001 / HEALTH-002 | **No** |
| **Latitude / longitude** | **Not in the List.** SLIP HEALTH-001, or OpenStreetMap where SLIP does not have the site | **No** |
| **Model tier** (teaching, regional, nursing post ...) | This project, from the SLIP category. Sets synthetic volumes only | **No** |

Where an official name differs from the SLIP name, the **official name is used**; the SLIP name is kept as \`slipName\`.

## Counts

### By Health Service Provider (HSP grouping is not official)

| HSP | Name | Codes |
|---|---|---|
${order.map((h) => `| ${h} | ${J.hspNames[h]} | ${J.byHsp[h] || 0} |`).join('\n')}
| | **Total** | **${E.length}** |

### By establishment type (official)

| Type | Codes |
|---|---|
${Object.entries(types).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

${E.filter((e) => e.mps).length} of the ${E.length} are Multi-Purpose Services.

### By model tier (this project's grouping, used only to size the synthetic volumes)

| Tier | Codes |
|---|---|
${Object.entries(tiers).map(([k, v]) => `| ${k} ${TIER[k]} | ${v} |`).join('\n')}

## Sites needing a note
`;
for (const e of E.filter((e) => e.hspNote)) m += `\n* **${e.code} ${e.name}** (${e.hsp}, basis \`${e.hspBasis}\`): ${e.hspNote}`;
m += `

### Positions not taken directly from SLIP (${locFlag.length}; ⚑ in the app where approximate)

`;
for (const e of locFlag) m += `* **${e.code} ${e.name}** (\`${e.locationStatus}\`): ${e.locationNote || ''}\n`;
m += `
Position status overall: ${Object.entries(count((e) => e.locationStatus)).map(([k, v]) => `${k} ${v}`).join(', ')}.

### HSP not taken from SLIP (${hspNon.length}; marked * below)

${hspNon.map((e) => `${e.code} ${e.short} (${e.hsp}, ${e.hspBasis})`).join('; ')}. \`crs\` = Department of Health Central Referral Service page; \`agreement\` = WACHS Service Agreement 2025-26; \`assumed\` = display grouping only, because the documents do not say.

`;
for (const h of order) {
  const rows = E.filter((e) => e.hsp === h);
  m += `## ${h}: ${J.hspNames[h]} (${rows.length})\n\n| Code | Official name | Type | MPS | Model tier | Region | District | Beds | Lat | Long | Position | HSP basis |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const e of rows) m += `| ${e.code} | ${esc(e.name)} | ${e.type || 'none'} | ${e.mps ? 'Y' : ''} | ${e.tier} | ${esc(e.region)} | ${esc(e.district)} | ${e.beds || '–'} | ${e.lat?.toFixed?.(4) ?? ''} | ${e.lon?.toFixed?.(4) ?? ''} | ${e.locationStatus} | ${e.hspBasis}${e.hspBasis !== 'slip' ? '*' : ''} |\n`;
  m += '\n';
}
m += `## Known gaps

* **No HSP, region or coordinates in the official List.** All three are this project's joins (SLIP HEALTH-001/-002, OpenStreetMap, the Central Referral Service page, the WACHS Service Agreement). The data custodian can replace them.
* **Peel Health Campus has two codes** (0145 and 0645) with EDDC = Y. 0645 is not in the Hospital Morbidity System Codes table and has no Est type. The app treats 0645 as the same site with no activity of its own (open question).
* **WA Virtual Hospital (0123)** has no physical ED. It is drawn at a placeholder point in the Perth CBD and grouped under WACHS for display only (open questions).
* SLIP flags ${J.slipCrossCheck.inSlipNotInList.map((x) => x.name).join(' and ')} as ED sites, but neither is in the List's EDDC set.
* Attribution: ${J._attribution}
`;
writeFileSync(new URL('../docs/ESTABLISHMENTS.md', import.meta.url), m);
console.log('Wrote docs/ESTABLISHMENTS.md:', E.length, 'codes,', sites, 'sites');
